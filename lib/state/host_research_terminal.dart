Future<Object?> _ssh(String operation, Map<String, Object?> arguments) =>
    HostClient.current!.call('runtime', 'ssh.$operation', arguments);
void _report(Object error) => HostClient.current?.reportError(error.toString());

class HostResearchTerminalController extends ResearchTerminalController {
  Timer? _timer;
  bool _polling = false;
  int _cursor = 0, _outputGeneration = -1;
  Future<void> _inputTail = Future.value();
  int _inputEpoch = 0;
  Map<String, Object?> get _connection => {
    'generation': state.connectionGeneration,
    'profile': state.activeProfileId,
  };
  @override
  ResearchTerminalState build() {
    final initial = projectHostState(
      ref,
      'research',
      decodeResearch,
      (value) => state = value,
    );
    terminal.onOutput = (text) => writeUserInput(text);
    terminal.onResize = (w, h, pw, ph) => resizeRemote(w, h);
    _timer = Timer.periodic(
      const Duration(milliseconds: 150),
      (_) => unawaited(_poll()),
    );
    ref.onDispose(() {
      _timer?.cancel();
      terminal.onOutput = null;
      terminal.onResize = null;
    });
    return initial;
  }

  Future<void> _poll() async {
    final client = HostClient.current;
    if (_polling || client == null || !client.connected) return;
    _polling = true;
    try {
      final result = await client.invoke('host.ssh.poll', {
        'cursor': _cursor,
        'generation': _outputGeneration,
      });
      if (!ref.mounted) return;
      final output = result['text'] as String? ?? '';
      // Responses generated by replaying terminal control sequences must not
      // be sent back into the remote shell as fresh user input.
      final callback = terminal.onOutput;
      terminal.onOutput = null;
      try {
        if (result['reset'] == true) {
          terminal.write('\x1bc');
          transcript.clear();
        }
        terminal.write(output);
      } finally {
        terminal.onOutput = callback;
      }
      transcript.append(output);
      _cursor = result['cursor'] as int;
      _outputGeneration = result['generation'] as int;
    } catch (_) {
      /* Connection banner covers transport failure. */
    } finally {
      _polling = false;
    }
  }

  Future<void> _call(
    String operation, [
    Map<String, Object?> arguments = const {},
  ]) async {
    await _ssh(operation, {..._connection, ...arguments});
  }

  void _queue(String operation, Map<String, Object?> arguments) {
    final captured = {..._connection, ...arguments};
    final epoch = _inputEpoch;
    _inputTail = _inputTail
        .then((_) async {
          if (epoch != _inputEpoch) return;
          await HostClient.current!.invoke('host.ssh.control', {
            'operation': operation,
            'arguments': captured,
          });
        })
        .catchError((Object error) {
          _inputEpoch++;
          _report(error);
        });
  }

  @override
  Future<void> reloadProfiles() => _call('reloadProfiles');
  @override
  Future<void> saveProfile(
    SshProfile profile, {
    String? password,
    String? privateKeyPem,
    String? passphrase,
  }) => _call('saveProfile', {
    'value': profile.toJson(),
    'password': password,
    'privateKeyPem': privateKeyPem,
    'passphrase': passphrase,
  });
  @override
  Future<void> deleteProfile(String id) => _call('deleteProfile', {'id': id});
  @override
  Future<void> connect(SshProfile profile) =>
      _call('connect', {'value': profile.toJson()});
  @override
  Future<({Duration elapsed, String? fingerprint})> testProfile(
    SshProfile profile, {
    String? password,
    String? privateKeyPem,
    String? passphrase,
  }) async {
    final value = wireMap(
      await _ssh('testProfile', {
        'value': profile.toJson(),
        'password': password,
        'privateKeyPem': privateKeyPem,
        'passphrase': passphrase,
      }),
    );
    return (
      elapsed: Duration(microseconds: value['elapsed'] as int),
      fingerprint: value['fingerprint'] as String?,
    );
  }

  @override
  Future<void> disconnect({
    bool bumpGeneration = true,
    bool invalidateConnectAttempts = true,
  }) => _call('disconnect');
  @override
  Future<void> releaseAll() => _call('releaseAll');
  @override
  Future<void> setAiContextLines(int lines) =>
      _call('aiContext', {'value': lines});
  @override
  Future<void> setBlockCtrlC(bool value) =>
      _call('blockCtrlC', {'value': value});
  @override
  void setCtrlLatched(bool value) => _queue('ctrlLatch', {'value': value});
  @override
  bool writeUserInput(String data, {bool force = false}) {
    if (!state.isConnected || HostClient.current?.connected != true) {
      return false;
    }
    _queue('input', {'data': data, 'force': force});
    return TerminalInputGuard.filter(
      data,
      blockInterrupt: !force && state.blockCtrlC,
    ).blockedInterrupt;
  }

  @override
  void resizeRemote(int columns, int rows) {
    if (columns < 2 || rows < 2 || !state.isConnected) return;
    unawaited(
      HostClient.current!
          .invoke('host.ssh.resize', {
            ..._connection,
            'cols': columns,
            'rows': rows,
          })
          .then<void>((_) {}, onError: _report),
    );
  }

  @override
  void clearInterruptBlockedFlash() => _queue('clearInterrupt', {});
  @override
  Future<void> refreshTmux() => _call('refreshTmux');
  @override
  Future<void> createTmuxSession(String name) =>
      _call('createTmux', {'name': name});
  @override
  Future<void> switchTmuxSession(String name) =>
      _call('switchTmux', {'name': name});
  @override
  Future<void> detachTmuxSession() => _call('detachTmux');
  @override
  Future<void> analyzeWithAi({String? userGoal}) =>
      _call('analyze', {'goal': userGoal});
  @override
  void clearProposal() => _queue('clearProposal', {});
  @override
  CommandProposal? editProposalCommand(String command) {
    final id = state.proposal?.id;
    final result = super.editProposalCommand(command);
    if (id != null) {
      _queue('editProposal', {'command': command, 'proposalId': id});
    }
    return result;
  }

  @override
  void executeApproved(ApprovedCommand approved) {
    if (approved.connectionGeneration != state.connectionGeneration ||
        approved.hostId != state.activeProfileId ||
        !state.isConnected ||
        HostClient.current?.connected != true) {
      throw StateError('连接已改变，命令未发送');
    }
    _queue('executeApproved', {
      'proposalId': approved.proposalId,
      'command': approved.command,
      'cwdHint': approved.cwdHint,
    });
  }

  @override
  ResearchFiles get files => HostResearchFiles(_connection);
  @override
  Future<ResearchWorkspaceSession> openWorkSession(
    String profileId,
    String directory,
  ) async {
    final captured = {..._connection, 'profile': profileId};
    final value = wireMap(
      await _ssh('work.open', {...captured, 'root': directory}),
    );
    return _HostResearchWorkspace(
      value['id'] as String,
      root: value['root'] as String,
      label: value['label'] as String,
      profileId: profileId,
      files: HostResearchFiles(captured),
      validate: () {
        if (state.connectionGeneration != captured['generation'] ||
            state.activeProfileId != profileId) {
          throw StateError('SSH 连接已变化');
        }
      },
    );
  }
}

class HostResearchFiles
    implements ResearchFiles, ResearchBinaryFiles, ResearchRecoveryFiles {
  HostResearchFiles(this.connection);
  final Map<String, Object?> connection;
  final _recoveries = <String, String>{};
  Future<Object?> _call(String method, Map<String, Object?> args) =>
      _ssh('files.$method', {...connection, ...args});
  @override
  String? recoveryPathFor(String path) => _recoveries[path];
  @override
  Future<String> absolute(String path) async =>
      await _call('absolute', {'path': path}) as String;
  @override
  Future<List<ResearchRemoteFile>> list(String path) async =>
      wireRows(await _call('list', {'path': path}))
          .map(
            (f) => ResearchRemoteFile(
              name: f['name'] as String,
              path: f['path'] as String,
              directory: f['directory'] == true,
              size: f['size'] as int,
            ),
          )
          .toList();
  @override
  Future<String> readText(String path) async =>
      await _call('readText', {'path': path}) as String;
  @override
  Future<List<int>> readBytes(
    String path, {
    int maxBytes = 8 * 1024 * 1024,
  }) async => base64Decode(
    await _call('readBytes', {'path': path, 'maxBytes': maxBytes}) as String,
  );
  @override
  Future<void> saveText(
    String path,
    String content, {
    required String original,
  }) async {
    final result = wireMap(
      await _call('saveText', {
        'path': path,
        'content': content,
        'original': original,
      }),
    );
    final recovery = result['recoveryPath'];
    if (recovery is String) _recoveries[path] = recovery;
  }

  @override
  Future<void> mkdir(String path) async {
    await _call('mkdir', {'path': path});
  }

  Future<void> _transfer(
    String method,
    String local,
    String remote,
    ResearchTransferToken token,
    void Function(int, int) progress,
  ) async {
    token.check();
    final id = const Uuid().v4();
    var polling = false;
    final timer = Timer.periodic(const Duration(milliseconds: 200), (_) async {
      if (polling) return;
      polling = true;
      try {
        if (token.cancelled) {
          await HostClient.current!.invoke('host.ssh.cancel', {'id': id});
        }
        final result = await HostClient.current!.invoke('host.ssh.poll', {
          'kind': 'transfer',
          'id': id,
        });
        progress(result['count'] as int, result['total'] as int);
      } catch (_) {
        /* The operation receipt remains authoritative. */
      } finally {
        polling = false;
      }
    });
    try {
      await _call(method, {'transferId': id, 'local': local, 'remote': remote});
    } finally {
      timer.cancel();
    }
  }

  @override
  Future<void> download(
    String remote,
    String local, {
    required ResearchTransferToken token,
    required void Function(int, int) progress,
  }) => _transfer('download', local, remote, token, progress);
  @override
  Future<void> upload(
    String local,
    String remote, {
    required ResearchTransferToken token,
    required void Function(int, int) progress,
  }) => _transfer('upload', local, remote, token, progress);
}

class _HostResearchWorkspace extends ResearchWorkspaceSession {
  _HostResearchWorkspace(
    this.id, {
    required super.root,
    required super.label,
    required super.profileId,
    required super.files,
    required super.validate,
  }) : super(
         command: (_, _, _, {onOutput, onComplete}) =>
             throw StateError('请通过宿主工作区调用命令'),
         openTerminal: (columns, rows) =>
             _HostResearchTerminal.open(id, columns, rows),
       );
  final String id;
  @override
  Future<String> call(
    String name,
    Map<String, dynamic> args,
    CancelToken token, {
    WorkspaceCommandOutput? onOutput,
    WorkspaceCommandCompletion? onComplete,
  }) async {
    validate();
    if (token.isCancelled) throw token.cancelError!;
    final callId = const Uuid().v4();
    var finished = false, polling = false;
    var cursor = 0, generation = -1;
    Future<void> poll() async {
      if (polling) return;
      polling = true;
      try {
        if (token.isCancelled) {
          await HostClient.current!.invoke('host.ssh.cancel', {'id': callId});
        }
        final result = await HostClient.current!.invoke('host.ssh.poll', {
          'kind': 'call',
          'id': callId,
          'cursor': cursor,
          'generation': generation,
        });
        final text = result['text'] as String? ?? '';
        if (text.isNotEmpty) onOutput?.call(text, false);
        cursor = result['cursor'] as int;
        generation = result['generation'] as int;
      } catch (_) {
        /* A read may race command admission. */
      } finally {
        polling = false;
      }
    }

    final timer = Timer.periodic(
      const Duration(milliseconds: 150),
      (_) => unawaited(poll()),
    );
    unawaited(
      token.whenCancel
          .then<void>((_) async {
            if (!finished) {
              await HostClient.current?.invoke('host.ssh.cancel', {
                'id': callId,
              });
            }
          })
          .catchError(_report),
    );
    try {
      final result =
          await _ssh('work.call', {
                'id': id,
                'callId': callId,
                'tool': name,
                'arguments': args,
              })
              as String;
      await poll();
      try {
        final data = wireMap(jsonDecode(result));
        onComplete?.call(
          WorkspaceCommandOutcome(
            exitCode: data['exit_code'] as int?,
            cancelled: data['cancelled'] == true,
            timedOut: data['timed_out'] == true,
          ),
        );
      } catch (_) {
        /* File replies do not carry command outcomes. */
      }
      return result;
    } finally {
      finished = true;
      timer.cancel();
    }
  }

  @override
  Future<void> close() async {
    await _ssh('work.close', {'id': id});
  }
}

class _HostResearchTerminal implements TerminalConnection {
  _HostResearchTerminal(this.id) {
    timer = Timer.periodic(
      const Duration(milliseconds: 100),
      (_) => unawaited(_poll()),
    );
  }
  static Future<TerminalConnection> open(
    String session,
    int cols,
    int rows,
  ) async {
    final value = wireMap(
      await _ssh('terminal.open', {'id': session, 'cols': cols, 'rows': rows}),
    );
    return _HostResearchTerminal(value['id'] as String);
  }

  final String id;
  final _output = StreamController<List<int>>();
  final _exit = Completer<int?>();
  Future<void> _writes = Future.value();
  late final Timer timer;
  bool polling = false, closed = false;
  int cursor = 0, generation = -1;
  @override
  Stream<List<int>> get output => _output.stream;
  @override
  Future<int?> get exitCode => _exit.future;
  Future<void> _poll() async {
    if (polling || closed) return;
    polling = true;
    try {
      final result = await HostClient.current!.invoke('host.ssh.poll', {
        'kind': 'terminal',
        'id': id,
        'cursor': cursor,
        'generation': generation,
      });
      if (closed) return;
      final text = result['text'] as String? ?? '';
      if (text.isNotEmpty) _output.add(utf8.encode(text));
      cursor = result['cursor'] as int;
      generation = result['generation'] as int;
      if (result['done'] == true && !_exit.isCompleted) {
        _exit.complete(result['exitCode'] as int?);
        timer.cancel();
      }
    } catch (error) {
      if (!closed) {
        _output.addError(error);
        if (!_exit.isCompleted) _exit.complete(null);
        timer.cancel();
      }
    } finally {
      polling = false;
    }
  }

  @override
  Future<void> write(List<int> bytes) {
    final encoded = base64Encode(bytes);
    return _writes = _writes.then((_) async {
      if (closed) throw StateError('终端已关闭');
      await HostClient.current!.invoke('host.ssh.control', {
        'operation': 'terminal.write',
        'arguments': {'id': id, 'bytes': encoded},
      });
    });
  }

  @override
  void resize(int columns, int rows) {
    if (!closed) {
      unawaited(
        HostClient.current!
            .invoke('host.ssh.resize', {
              'kind': 'terminal',
              'id': id,
              'cols': columns,
              'rows': rows,
            })
            .then<void>((_) {}, onError: _report),
      );
    }
  }

  @override
  Future<void> close() async {
    if (closed) return;
    closed = true;
    timer.cancel();
    try {
      await _ssh('terminal.close', {'id': id});
    } finally {
      if (!_exit.isCompleted) _exit.complete(null);
      unawaited(_output.close());
    }
  }
}
